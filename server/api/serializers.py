class CartItemSerializer(serializers.ModelSerializer):
    # 1. Used for returning full details to the frontend (GET requests)
    product_variant_detail = ProductVariantSerializer(source='product_variant', read_only=True)
    #product_variant_id = ProductVariantSerializer(source='product_variant', read_only=True)
    # 2. Matches your frontend payload key exactly (POST/PUT requests)
    product_variant = serializers.PrimaryKeyRelatedField(
        queryset=ProductVariant.objects.all()
    )
    
    subtotal = serializers.SerializerMethodField()

    class Meta:
        model = CartItem
        fields = ['id', 'cart', 'product_variant', 'product_variant_detail', 'quantity', 'subtotal', 'added_at']

    def get_subtotal(self, obj):
        price = obj.product_variant.price_override if obj.product_variant.price_override is not None else obj.product_variant.product.price
        return float(price) * obj.quantity

